//! Keyboard actions. Viewer shortcuts live in the "Viewer" key context, which
//! is never an ancestor of a text field, so typing a comment can't trigger
//! playback.

use gpui::{actions, App, KeyBinding};

actions!(
    plate,
    [
        TogglePlay,
        PlayForward,
        PlayReverse,
        Pause,
        StepForward,
        StepBack,
        StepForward10,
        StepBack10,
        GoStart,
        GoEnd,
        SetIn,
        SetOut,
        ClearInOut,
        ChannelRed,
        ChannelGreen,
        ChannelBlue,
        ChannelAlpha,
        ChannelLuma,
        ChannelRgb,
        ZoomFit,
        Zoom100,
        ZoomIn,
        ZoomOut,
        ExposureUp,
        ExposureDown,
        ResetViewer,
        ToggleDraw,
        UndoShape,
        Escape,
        ToggleMute,
        ToggleLoop,
        OpenFile,
        OpenFolder,
        SaveFrame,
        Quit,
        ToggleComments,
        ToggleBin,
        ToggleFullscreen,
        ToggleCompare,
        CycleCompareMode,
        NextClip,
        PrevClip,
        NextComment,
        PrevComment,
        FocusComment,
        ToggleProbe,
        ShowHelp,
        ToolPen,
        ToolArrow,
        ToolLine,
        ToolRect,
        ToolEllipse,
        ToolText,
        ToolEraser,
        NextColor,
        ColorspaceModal,
        DisplayModal,
        PrevLayer,
        NextLayer,
        ToggleGuides,
        ToggleCaptions,
        GuidesModal,
        CaptionsModal,
        UiScaleUp,
        UiScaleDown,
        UiScaleReset,
    ]
);

pub fn bind_keys(cx: &mut App) {
    let v = Some("Viewer");
    let d = Some("Viewer && drawing");
    let g = Some("Plate");
    cx.bind_keys([
        KeyBinding::new("space", TogglePlay, v),
        KeyBinding::new("l", PlayForward, v),
        KeyBinding::new("j", PlayReverse, v),
        KeyBinding::new("k", Pause, v),
        KeyBinding::new("right", StepForward, v),
        KeyBinding::new("left", StepBack, v),
        KeyBinding::new("shift-right", StepForward10, v),
        KeyBinding::new("shift-left", StepBack10, v),
        KeyBinding::new("home", GoStart, v),
        KeyBinding::new("end", GoEnd, v),
        KeyBinding::new("i", SetIn, v),
        KeyBinding::new("o", SetOut, v),
        KeyBinding::new("u", ClearInOut, v),
        KeyBinding::new("r", ChannelRed, v),
        KeyBinding::new("g", ChannelGreen, v),
        KeyBinding::new("b", ChannelBlue, v),
        KeyBinding::new("a", ChannelAlpha, v),
        KeyBinding::new("y", ChannelLuma, v),
        KeyBinding::new("c", ChannelRgb, v),
        KeyBinding::new("f", ZoomFit, v),
        KeyBinding::new("h", Zoom100, v),
        KeyBinding::new("=", ZoomIn, v),
        KeyBinding::new("+", ZoomIn, v),
        KeyBinding::new("-", ZoomOut, v),
        KeyBinding::new(".", ExposureUp, v),
        KeyBinding::new(",", ExposureDown, v),
        KeyBinding::new("backspace", ResetViewer, v),
        KeyBinding::new("d", ToggleDraw, v),
        KeyBinding::new("ctrl-z", UndoShape, v),
        KeyBinding::new("escape", Escape, v),
        KeyBinding::new("m", ToggleMute, v),
        KeyBinding::new("shift-l", ToggleLoop, v),
        KeyBinding::new("w", ToggleCompare, v),
        KeyBinding::new("shift-w", CycleCompareMode, v),
        KeyBinding::new("down", NextClip, v),
        KeyBinding::new("up", PrevClip, v),
        KeyBinding::new("]", NextComment, v),
        KeyBinding::new("[", PrevComment, v),
        KeyBinding::new("enter", FocusComment, v),
        KeyBinding::new("p", ToggleProbe, v),
        KeyBinding::new("'", ToggleGuides, v),
        KeyBinding::new("alt-left", PrevLayer, v),
        KeyBinding::new("alt-right", NextLayer, v),
        KeyBinding::new("s", ToggleCaptions, v),
        KeyBinding::new("shift-/", ShowHelp, v),
        KeyBinding::new("?", ShowHelp, v),
        KeyBinding::new("tab", ToggleComments, v),
        KeyBinding::new("shift-tab", ToggleBin, v),
        KeyBinding::new("1", ToolPen, d),
        KeyBinding::new("2", ToolArrow, d),
        KeyBinding::new("3", ToolLine, d),
        KeyBinding::new("4", ToolRect, d),
        KeyBinding::new("5", ToolEllipse, d),
        KeyBinding::new("6", ToolText, d),
        KeyBinding::new("0", ToolEraser, d),
        KeyBinding::new("x", NextColor, d),
        KeyBinding::new("ctrl-o", OpenFile, g),
        KeyBinding::new("ctrl-shift-o", OpenFolder, g),
        KeyBinding::new("ctrl-s", SaveFrame, g),
        KeyBinding::new("ctrl-q", Quit, g),
        KeyBinding::new("ctrl-b", ToggleBin, g),
        KeyBinding::new("f11", ToggleFullscreen, g),
        KeyBinding::new("ctrl-i", ColorspaceModal, g),
        KeyBinding::new("ctrl-d", DisplayModal, g),
        KeyBinding::new("ctrl-=", UiScaleUp, g),
        KeyBinding::new("ctrl-+", UiScaleUp, g),
        KeyBinding::new("ctrl-shift-=", UiScaleUp, g),
        KeyBinding::new("ctrl--", UiScaleDown, g),
        KeyBinding::new("ctrl-0", UiScaleReset, g),
    ]);
}

